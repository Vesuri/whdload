#!/usr/bin/env bash
# Boot any installed WHDLoad archive (a Retroplay-style .lha) without a games/<Game> directory,
# to try a candidate before bringing it in. `make run` in try/ calls this.
#   common/try.sh [run|stop|unpack|list]
#   common/try.sh server serve | server <command...>
#                        boot it under common/tools/game_server.py (DEBUG=1), then send it
#                        the server's built-in commands: shot <png>, wait <s>, quit, ...
#   ARCHIVE=file         the archive (relative to where make started); default: the newest
#                        .lha, .lzh, .lzx or .zip in that directory
#   VARIANT=name         which slave, when the archive has several (default: the first);
#                        `list` shows them
#   SLAVE=path           another slave file in place of the shipped one
#   FORCE=1              unpack again
# Every other common/run.sh option applies: SETUP, WHD_ARGS, DEBUG, WARP, INSTANCE, ...
#
# The archive is unpacked once, into try/tmp/<archive name>/tmp/game/; its SHA-256 is recorded
# beside it, and a changed archive is unpacked again. Nothing there is tracked. A generated
# game.conf in try/tmp/<archive name>/ names the slaves; KICKS is every Kickstart in
# $AMIGA_SHARE/Kickstarts, since which one a slave wants is not known. The icon's tooltypes
# are not read: pass the options they set (CUSTOM1=..., PRELOAD) in WHD_ARGS.
set -euo pipefail
. "$(dirname "$0")/lib.sh"
# shellcheck disable=SC1091
. "$COMMON/env.sh"

ACTION="${1:-run}"
case "$ACTION" in run|stop|unpack|list|server) ;; *) die "usage: try.sh [run|stop|unpack|list|server ...]" ;; esac
HERE="${CALLER_DIR:-$PWD}"
TRY_DIR="$REPO/try"

# The archive.
if [ -n "${ARCHIVE:-}" ]; then
  archive="$(caller_path "$ARCHIVE")"
else
  archive="$(ls -t "$HERE"/*.[lL][hH][aA] "$HERE"/*.[lL][zZ][hHxX] "$HERE"/*.[zZ][iI][pP] 2>/dev/null | head -n 1 || true)"
  [ -n "$archive" ] || die "no archive in $HERE: download one there, or pass ARCHIVE=<file>"
fi
[ -f "$archive" ] || die "no archive $archive"
name="$(basename "$archive")"
name="${name%.*}"
name="$(printf '%s' "$name" | tr -c 'A-Za-z0-9_.-' '_')"
TRY_ROOT="$TRY_DIR/tmp/$name"
mkdir -p "$TRY_ROOT"
[ ! -L "$TRY_ROOT" ] || die "$TRY_ROOT must not be a symlink"

# Unpack into a fresh, empty directory, when not done yet or when the archive changed.
sum="$(shasum -a 256 "$archive" | cut -d' ' -f1)"
game="$TRY_ROOT/tmp/game"
if [ "${FORCE:-0}" = 1 ] || [ ! -d "$game" ] || [ "$(cat "$TRY_ROOT/archive.sha256" 2>/dev/null)" != "$sum" ]; then
  rm -rf "$game" "$TRY_ROOT/archive.sha256"
  mkdir -p "$TRY_ROOT/tmp"
  stage="$(mktemp -d "$TRY_ROOT/tmp/unpack.XXXXXX")"
  case "$archive" in
    *.[lL][hH][aA]|*.[lL][zZ][hH]) "$LHA" "xqw=$stage" "$archive" ;;
    *.[zZ][iI][pP]) unzip -q "$archive" -d "$stage" ;;
    *.[lL][zZ][xX]) command -v unar > /dev/null || die "unar is needed for $archive"
                    unar -q -o "$stage" "$archive" ;;
    *) die "not an archive: $archive" ;;
  esac
  mv "$stage" "$game"
  chmod -R u+w "$game"
  echo "$sum" > "$TRY_ROOT/archive.sha256"
  echo "unpacked $(basename "$archive") into try/tmp/$name/tmp/game"
fi

# The slaves, in the archive's top level or in a drawer one level down; the game.conf naming
# them is written on every run.
slaves=()
while IFS= read -r f; do slaves+=("${f#"$game"/}"); done < <(
  find "$game" -mindepth 1 -maxdepth 2 -type f -iname '*.slave' | LC_ALL=C sort)
[ "${#slaves[@]}" -gt 0 ] || die "no slave in $(basename "$archive")"
kicks=""
for k in "$AMIGA_SHARE"/Kickstarts/*; do
  case "$k" in *.RTB) ;; *) [ ! -f "$k" ] || kicks="$kicks ${k##*/}" ;; esac
done
variants="" cases=""
for s in "${slaves[@]}"; do
  case "$s" in */*) dir="${s%/*}" file="${s##*/}" ;; *) dir=. file="$s" ;; esac
  v="$(printf '%s' "${file%.*}" | tr -c 'A-Za-z0-9_-' '_')"
  case " $variants " in *" $v "*) v="${v}_$(printf '%s' "$dir" | tr -c 'A-Za-z0-9_-' '_')" ;; esac
  variants="${variants:+$variants }$v"
  cases="$cases  $v) GAME_DIR=$(printf '%q' "$dir") SLAVE_FILE=$(printf '%q' "$file") ;;
"
done
cat > "$TRY_ROOT/game.conf" <<EOF
# Generated by common/try.sh from $(basename "$archive"); written on every run.
TITLE='$name'
VARIANTS='$variants'
case "\${VARIANT:-}" in
${cases}esac
SLAVE=original
KICKS='${kicks# }'
SETUP=a500
WHD_DEFAULTS='PRELOAD SPLASHDELAY=0 NOREQ'
EOF

export TRY_ROOT GAME="$name"
case "$ACTION" in
  unpack) exit 0 ;;
  list)
    ( . "$TRY_ROOT/game.conf"
      for v in $VARIANTS; do
        VARIANT="$v"; . "$TRY_ROOT/game.conf"
        printf '%-24s %s\n' "$v" "$GAME_DIR/$SLAVE_FILE"
      done ) ;;
  server)
    shift
    cd "$TRY_ROOT"
    exec python3 "$COMMON/tools/game_server.py" "$@" ;;
  *) exec "$COMMON/run.sh" "$ACTION" ;;
esac
