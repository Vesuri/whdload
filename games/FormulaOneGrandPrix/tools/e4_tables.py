#!/usr/bin/env python3
"""E4: the polygon renderer's CPU-only chip data, moved to fast RAM, and its operand table.

  e4_tables.py [--out tmp/slave/include/e4.i]

The filler (h0+$1F388) and the edge tracer (h0+$1EABA) keep their data in f1gp's chip
hunks 2 and 3: the tracer writes each edge's X list into a bump-allocated pool and the
filler reads it back with the span mask table and its jump-offset words. Only the CPU
uses these areas, and every access goes through an absolute (relocated) address of the
area's start, an in-area limit or a pointer derived from one. The slave copies each
region to fast RAM at the first live epoch and adds the distance to every relocated
long that holds an address inside it, and to the pointer cells listed here that the
game derives at run time. Pointers already stored elsewhere keep the chip original,
which then still holds the same bytes. The output contains offsets derived from the
game and must stay under tmp/.
"""
import argparse
from pathlib import Path
import struct
import sys

sys.path.insert(0, str(Path(__file__).resolve().parent))
from e2_tables import hunks                                                   # noqa: E402
from slave_inputs import ROOT, verify                                         # noqa: E402

# (hunk, low, high): the moved regions.
REGIONS = (
    (3, 0x200, 0x704),        # span masks and word offsets for X 0-320 (built by h2+$1E936)
    (3, 0x112f8, 0x14f84),    # edge pool to the end of hunk 3 (limit h3+$14D90 plus one edge)
    (2, 0x1e804, 0x1e810),    # the fillers' jump-offset words h2+$1E804 and h2+$1E80E
)
# (hunk, offset): run-time pointer cells into a region: the pool cursor and its saved copy.
CELLS = ((0, 0x1f03a), (2, 0x2816c))


def analyse():
    verify()
    data, relocs = hunks()
    operands, ends = [], []
    for h, lo, hi in REGIONS:
        if lo % 4 or hi % 4:
            raise SystemExit(f'region h{h}+{lo:x} is not long aligned')
    for src in sorted(relocs):
        for at, target in sorted(relocs[src].items()):
            value = struct.unpack_from('>I', data[src], at)[0]
            for h, lo, hi in REGIONS:
                if target == h and lo <= value < hi:
                    operands.append((src, at))
                elif target == h and value == hi:
                    ends.append((src, at))      # an end bound of a larger area (h3's clear)
    for h, at in CELLS:
        if (h, at) not in operands:
            operands.append((h, at))
    return operands, ends


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--out', default=str(ROOT/'tmp/slave/include/e4.i'))
    args = parser.parse_args()
    operands, ends = analyse()
    out = Path(args.out).resolve()
    if not out.is_relative_to(ROOT/'tmp'):
        raise ValueError('output must stay in project tmp/')
    lines = ['; Generated by tools/e4_tables.py from the pinned f1gp; never commit this file.',
             f'E4_REGIONS = {len(REGIONS)}', f'E4_OPERANDS = {len(operands)}']
    size, regions = 0, []
    for h, lo, hi in REGIONS:
        size += lo & 15                 # the copy keeps the original's alignment modulo 16
        regions.append(f'        dc.w {h}\n        dc.l ${lo:x},${hi:x},${size:x}')
        size = (size + hi - lo + 15) & ~15
    lines += [f'E4_DATA_SIZE = ${size:x}', 'e4_regions'] + regions
    # Bits 28-31: the hunk holding the long.
    lines += ['e4_operands'] + [f'        dc.l ${h << 28 | at:x}' for h, at in operands]
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text('\n'.join(lines)+'\n')
    print(f'{len(operands)} operands, {size} bytes, end bounds left alone: '
          + ', '.join(f'h{h}+{at:x}' for h, at in ends))


if __name__ == '__main__':
    main()
