#!/usr/bin/env python3
"""F5: checksums the slave compares before it patches an f1gp file.

  f5_sites.py [--out tmp/slave/include/f5.i] [--game PATH]

From the pinned (or given) 582,992-byte file:
- F5_SITES: every optional hook range of the slave (the PERF_RANGE list B4 audits), as
  (hunk, offset, length) without the bytes of relocated longwords, which depend on the
  load address, or of the operands a hook reads from the file itself (READ), and F5_SUM
  over their bytes. If an edited file differs there, the slave leaves the developer
  options' patches out instead of patching changed code.
- NAMES_SUM over the 80 name fields at h2+$2AF52 (40 drivers of 24 bytes, then 40 team
  and engine names of 13), each up to and including its terminator: the slave replaces
  the names with the 1991 season's only if every visible name is the stock one. Bytes
  after a terminator do not count; F1GP-Ed's Project/New leaves old names' tails there.
The sum is the slave's: rotate left one bit, then add the byte. No game bytes are written.
"""
import argparse
import struct
from pathlib import Path

from check_disabled import SOURCE, ranges
from f1_diff import hunks, relocs
from slave_inputs import ROOT, verify

GAME = ROOT/'tmp/game/FormulaOneGrandPrix4Disk/data/f1gp'
NAMES = (2, 0x2af52, ((40, 24), (40, 13)))
# c2_hud_gear saves its ADDA.W operand (the gear's place, which F1GP-Ed's Graphics window
# writes) from h2+$1F92A before it patches the site; the second, h2+$1F92E, lies after
# it. F6 reads the speed factor base (F1GP-Ed's Speed Factor) from h0+$29A7E before it
# patches the site.
READ = {(2, 0x1f92a+k) for k in range(2)} | {(0, 0x29a7e+k) for k in range(2)}


def checksum(data, total=0):
    for byte in data:
        total = (((total << 1) | (total >> 31)) & 0xffffffff) + byte & 0xffffffff
    return total


def sites(game):
    layout = {h: (o, n) for h, o, n in hunks(game)}
    moved = {(h, o+k) for (h, o) in relocs(game) for k in range(4)} | READ
    out, seen = [], set()
    for r in ranges(SOURCE.read_text()):
        h, start = r['hunk'], r['offset']
        if (h, start) in seen:      # an alternative hook of the same range
            continue
        seen.add((h, start))
        run = None
        for o in range(start, start+r['size']):
            if (h, o) in moved:
                run = None
            elif run and run[1]+run[2] == o:
                run[2] += 1
            else:
                run = [h, o, 1]
                out.append(run)
    total = 0
    for h, o, n in out:
        base = layout[h][0]
        total = checksum(game[base+o:base+o+n], total)
    return [tuple(s) for s in out], total


def names(game):
    layout = {h: (o, n) for h, o, n in hunks(game)}
    h, at, fields = NAMES
    at += layout[h][0]
    total = 0
    for count, size in fields:
        for _ in range(count):
            field = game[at:at+size]
            end = field.find(0)
            total = checksum(field[:size if end < 0 else end+1], total)
            at += size
    return total


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--out', default=str(ROOT/'tmp/slave/include/f5.i'))
    parser.add_argument('--game')
    args = parser.parse_args()
    out = Path(args.out).resolve()
    if not out.is_relative_to(ROOT/'tmp'):
        raise ValueError('output must stay in project tmp/')
    if not args.game:
        verify()
    game = Path(args.game or GAME).read_bytes()
    assert len(game) == 582992
    table, total = sites(game)
    lines = ['; Generated by tools/f5_sites.py from the pinned f1gp; never commit this file.',
             f'F5_SUM = ${total:08x}', f'NAMES_SUM = ${names(game):08x}', 'f5_sites']
    lines += [f'        dc.w {h},{n}\n        dc.l ${o:x}' for h, o, n in table]
    lines.append('        dc.w -1')
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text('\n'.join(lines)+'\n')
    print(f'{len(table)} runs, {sum(n for *_, n in table)} bytes; F5_SUM ${total:08x}; NAMES_SUM ${names(game):08x}')


if __name__ == '__main__':
    main()
