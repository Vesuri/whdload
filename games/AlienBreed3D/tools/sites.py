#!/usr/bin/env python3
"""Enhanced resolution's geometry sites (resolution plan steps 5 and 6) into the slave's source.

    python3 tools/sites.py SITES.csv stride > src/stride.s
    python3 tools/sites.py SITES.csv sites > src/sites.s

SITES.csv is the step 5 site analysis (`;`-separated: offset, bytes, text, action, pos,
size, old, new, group, note; offsets are game offsets of the $c4dc executable, `new` the
192x160 value). It is made at analysis time from the disassembly and stays in ignored
`tmp/`; what is written here holds offsets and values only.

Every `imm` site whose 96x80 value is a whole number k of 416-byte lines (row steps,
unrolled displacements, line offsets) becomes `k*DS_STRIDE`: a PL_W or PL_L of the CUSTOM5
patch list, the same in both views, the stride being the build's (display.s). Not `midpt`
(fromPt + 40 lines, $32e8 and $3e58): nothing reads it, and Psygore's slave replaces the
one at $3e58 with a jsr to `_waitvbl`, which keeps its 16640. The row tables
(`timeslarge`, the polygons' rows) are rescaled by `_ds_stride` in display.s. At 1188 the
sky's unrolled displacements no longer fit a signed word: the game's sky runs only in a
LORES build (800), the 1x1 renderer draws its own.

`sites` writes the per-view table (display.s `SITE`: size, offset, the 192x160 value, the
288x240 one, the 96x80 one) of the other `imm` sites (centres, clips, scales). Each is
linear in the scale S (96x80 at 1, 192x160 at 2), so the 288x240 value is 2 * new - old
(47, 95: 143; 79, 159: 239; 41, 81: 121). Not the `op` sites (shift counts): a shift
cannot multiply by 3, so `src/hires.s` does them in code (`_t_x128`, `_t_fstep`,
`_t_fstep2`, `_t_index`, `_t_pvert`), and neither the ones it does otherwise: the objects'
`asl.l #7` before `sub.l eye` (`_t_eye`), glass and bitmaps' sizes (`_t_size`), the
floors' `asl.l #7` that undo an `asr.l #7` (not a scale). One more: the floors' first
line, `adda.l #17056,a6` at $1dab2 (41 lines; 81 at 160, 121 at 240).
"""
import csv
import sys

MORE = [  # (size, field's game offset, 192x160, 288x240, 96x80, note)
    (4, 0x1dab4, '81*DS_STRIDE', '121*DS_STRIDE', '41*DS_STRIDE',
     'floors: a6 = fromPt + the first floor line'),
]


def sites(path):
    rows = list(csv.DictReader(open(path), delimiter=';'))
    out = ['; Generated by tools/sites.py: each view\'s value at the geometry sites (SITE size,',
           '; game offset of the field, the 192x160 value, the 288x240 one, the 96x80 one;',
           '; the group and what it is).']
    n = 0
    for r in rows:
        if r['action'] != 'imm':
            continue
        off = int(r['offset'].lstrip('$'), 16)
        old = int(r['old'], 0)
        if old == 0 or old % 416 == 0:
            continue        # the stride's (stride.s)
        new = int(r['new'], 0)
        note = '%s: %s' % (r['group'], r['note'].split(':')[0].split('(')[0].strip())
        out.append('\tSITE\t%s,$%x,%s,%s,%s\t;%s' % (r['size'], off + int(r['pos']), fmt(new),
                                                    fmt(2 * new - old), fmt(old), note[:50]))
        n += 1
    for size, at, small, full, old, note in MORE:
        out.append('\tSITE\t%d,$%x,%s,%s,%s\t;%s' % (size, at, small, full, old, note))
        n += 1
    out.insert(3, '; %d sites.' % n)
    print('\n'.join(out))


def fmt(v):
    return '$%x' % (v & 0xffffffff) if v < 0 or v > 255 else '%d' % v


def main(path):
    rows = list(csv.DictReader(open(path), delimiter=';'))
    out = ['; Generated by tools/sites.py: the line stride, 416 -> DS_STRIDE bytes, at every',
           '; site that steps a whole number of lines (game offset, lines; the group and what',
           '; it is).']
    n = 0
    for r in rows:
        if r['action'] != 'imm' or r['group'] == 'swap' or r['offset'] == '$1dab2':
            continue        # midpt ($32e8, $3e58): no reader, and $3e58 is _waitvbl's jsr;
                            # $1dab2 is a site of each view (sites)
        old = int(r['old'], 0)
        if old == 0 or old % 416:
            continue
        k = old // 416
        size, at = int(r['size']), int(r['offset'].lstrip('$'), 16) + int(r['pos'])
        if size == 2 and r['group'] != 'sky' and abs(k) * 1188 > 32767:
            sys.exit('%s: %d lines do not fit a word' % (r['offset'], k))
        note = '%s: %s' % (r['group'], r['note'].split(':')[0].split('(')[0].strip())
        out.append('\tPL_%s\t$%x,%d*DS_STRIDE\t;%s' % ('W' if size == 2 else 'L', at, k, note[:60]))
        n += 1
    out.insert(3, '; %d sites.' % n)
    print('\n'.join(out))


if __name__ == '__main__':
    if len(sys.argv) != 3 or sys.argv[2] not in ('stride', 'sites'):
        sys.exit(__doc__)
    (main if sys.argv[2] == 'stride' else sites)(sys.argv[1])
