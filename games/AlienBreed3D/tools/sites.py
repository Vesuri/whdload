#!/usr/bin/env python3
"""Enhanced resolution's geometry sites (resolution plan step 5) into the slave's source.

    python3 tools/sites.py SITES.csv stride > src/stride.s
    python3 tools/sites.py SITES.csv sites > src/sites.s

SITES.csv is the step 5 site analysis (`;`-separated: offset, bytes, text, action, pos,
size, old, new, group, note; offsets are game offsets of the $c4dc executable). It is made
at analysis time from the disassembly and stays in ignored `tmp/`; what is written here
holds offsets and values only.

Every `imm` site whose 96x80 value is a whole number of 416-byte lines (row steps, unrolled
displacements, line offsets) becomes the same number of DS_STRIDE-byte lines: a PL_W or
PL_L of the CUSTOM5 patch list, the same in both views. Not `midpt` (fromPt + 40 lines,
$32e8 and $3e58): nothing reads it, and Psygore's slave replaces the one at $3e58 with a
jsr to `_waitvbl`, which keeps its 16640. The row tables (`timeslarge`, the
polygons' rows) are rescaled by `_ds_stride` in display.s.

`sites` writes the per-view table (display.s `SITE`: size, offset, the 192x160 value, the
96x80 one) of the other `imm` sites (centres, clips, scales) and the `op` sites (shift
counts), but not those the analysis got wrong or that display.s does in code:
- the floors' `asl.l #7` at $1d5dc $1d622 $1d820 $1d882 undo an `asr.l #7` a few
  instructions before (the edge's interpolation): not a scale;
- the objects' `asl.l #7` before `sub.l eye` ($21478 $21862 $21e26): the eye height must
  double too, so `_t_eye` doubles after the subtraction instead;
and with one more: the polygons' vertex x, `asr.l #8,d2` at $21dd6 (to #7).
"""
import csv
import sys

STRIDE = 800


NOT_OPS = {0x1d5dc, 0x1d622, 0x1d820, 0x1d882, 0x21478, 0x21862, 0x21e26}
MORE = [  # (size, field's game offset, 192x160 value, 96x80 value, note)
    (2, 0x21dd6, 0xee82, 0xe082, 'objects: polygon vertex x, asr.l #8,d2 -> #7'),
]


def sites(path):
    rows = list(csv.DictReader(open(path), delimiter=';'))
    out = ['; Generated by tools/sites.py: each view\'s value at the geometry sites (SITE size,',
           '; game offset of the field, the 192x160 value, the 96x80 one; the group and what it is).']
    n = 0
    for r in rows:
        off = int(r['offset'].lstrip('$'), 16)
        if r['action'] == 'imm':
            old = int(r['old'], 0)
            if old == 0 or old % 416 == 0:
                continue        # the stride's (stride.s)
            new = int(r['new'], 0)
        elif r['action'] == 'op' and off not in NOT_OPS:
            old, new = int(r['old'].replace('$', '0x'), 16), int(r['new'].replace('$', '0x'), 16)
        else:
            continue
        note = '%s: %s' % (r['group'], r['note'].split(':')[0].split('(')[0].strip())
        out.append('\tSITE\t%s,$%x,%s,%s\t;%s' % (r['size'], off + int(r['pos']), fmt(new), fmt(old),
                                                 note[:50]))
        n += 1
    for size, at, new, old, note in MORE:
        out.append('\tSITE\t%d,$%x,%s,%s\t;%s' % (size, at, fmt(new), fmt(old), note))
        n += 1
    out.insert(2, '; %d sites.' % n)
    print('\n'.join(out))


def fmt(v):
    return '$%x' % (v & 0xffffffff) if v < 0 or v > 255 else '%d' % v


def main(path):
    rows = list(csv.DictReader(open(path), delimiter=';'))
    out = ['; Generated by tools/sites.py: the line stride, 416 -> %d bytes, at every site' % STRIDE,
           '; that steps a whole number of lines (game offset, value; the group and what it is).']
    n = 0
    for r in rows:
        if r['action'] != 'imm' or r['group'] == 'swap':
            continue        # midpt ($32e8, $3e58): no reader, and $3e58 is _waitvbl's jsr
        old = int(r['old'], 0)
        if old == 0 or old % 416:
            continue
        new = old // 416 * STRIDE
        size, at = int(r['size']), int(r['offset'].lstrip('$'), 16) + int(r['pos'])
        if size == 2 and not -32768 <= new <= 65535:
            sys.exit('%s: %d does not fit a word' % (r['offset'], new))
        note = '%s: %s' % (r['group'], r['note'].split(':')[0].split('(')[0].strip())
        out.append('\tPL_%s\t$%x,%d\t\t;%s' % ('W' if size == 2 else 'L', at, new, note[:60]))
        n += 1
    out.insert(2, '; %d sites.' % n)
    print('\n'.join(out))


if __name__ == '__main__':
    if len(sys.argv) != 3 or sys.argv[2] not in ('stride', 'sites'):
        sys.exit(__doc__)
    (main if sys.argv[2] == 'stride' else sites)(sys.argv[1])
