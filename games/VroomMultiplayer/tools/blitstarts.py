#!/usr/bin/env python3
"""Write src/blitwait.i: the original Vroom slave's blitter waits at the Multiplayer's sites.

    python3 tools/blitstarts.py MEMORY.bin > src/blitwait.i

MEMORY.bin is chip memory from 0 at the program's entry ($3658, `BOOT_BREAK`; v1). Vroom's
original slave (Mr.Larmer) made every `move.w Dn,$58(a6)` (Dn = d0, d1, d4, d5 or d6) in
the renderer, $11000-$19C00, a `jsr` to a trampoline that starts the blit and waits for it,
and the five `btst #6,2(a6); bne.s *-6` waits of the init code a `nop; jsr WaitBlit`. The
Multiplayer's renderer is $13000-$1B300 and its init code's waits $3C80-$3D40. Only what a
linear decode (capstone) shows as those instructions is listed.
"""
import sys
import capstone

TRAMP = {0: 0x10C, 1: 0x112, 4: 0x118, 5: 0x11E, 6: 0x124}

def main():
    m = open(sys.argv[1], 'rb').read()
    md = capstone.Cs(capstone.CS_ARCH_M68K, capstone.CS_MODE_BIG_ENDIAN | capstone.CS_MODE_M68K_000)
    starts, waits = [], []
    pc = 0x3600
    while pc < 0x1B300:
        got = False
        for i in md.disasm(m[pc:0x1B300], pc):
            got = True
            pc = i.address + i.size
            if i.mnemonic == 'move.w' and i.op_str.endswith(', $58(a6)') and i.op_str[0] == 'd':
                r = int(i.op_str[1])
                if 0x13000 <= i.address < 0x1B300 and r in TRAMP:
                    starts.append((i.address, r))
            if (i.mnemonic == 'btst.b' and i.op_str == '#$6, $2(a6)' and 0x3C80 <= i.address < 0x3D40
                    and m[i.address + 6:i.address + 8] == b'\x66\xf8'):
                waits.append(i.address)
        if not got or pc < 0x1B300:
            pc += 2
    print('; Generated by tools/blitstarts.py from a memory image at $3658 (v1): the')
    print("; original Vroom slave's blitter waits at Vroom Multiplayer's sites.")
    print(f'; {len(starts)} blitter starts move.w Dn,$58(a6) -> jsr $10C-$124.w (WaitBlit0-6)')
    print('BLITWAIT_STARTS	MACRO')
    for a, r in starts:
        print(f'		PL_L	${a:X},$4EB80000+${TRAMP[r]:X}	; move.w d{r},$58(a6)')
    print('		ENDM')
    print(f'; {len(waits)} waits btst #6,2(a6); bne.s *-6 -> nop; jsr WaitBlit')
    print('BLITWAIT_LOOPS	MACRO')
    for a in waits:
        print(f'		PL_PS	${a + 2:X},WaitBlit	; (nop at ${a:X})')
        print(f'		PL_W	${a:X},$4E71')
    print('		ENDM')

main()
