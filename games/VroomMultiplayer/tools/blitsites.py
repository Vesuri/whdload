#!/usr/bin/env python3
"""tools/blitsites.py MEMORY.bin > src/blitsites.i

The blitter starts whose wait Enhanced framerate can leave to the game (games/Vroom's
tools/blitsites.py, its phase E step 18, at the Multiplayer's addresses). src/blitwait.i
makes every blitter start `move.w Dn,$58(a6)` in the renderer a `jsr $10C-$124.w`: start the
blit, then wait for it. Many are followed, in straight-line code, by the game's own wait
before its next blit (`btst #6,2(a6)` or `btst #6,$DFF002`, or `jsr` of the queue waits
$11FDE, $11FA6, $11FC2). A site qualifies when every instruction up to that wait touches no
memory but the custom chips through a6 (a `lea` is fine): no branch, call or return, no
other blitter start, no CPU access that might meet the blit.

MEMORY.bin is chip memory from 0 at the program's entry ($3658, v1; the sites still read
`move.w Dn,$58(a6)` there). The sites are src/blitwait.i's. Writes a macro of one PL_L per
site: a `jsr` to the matching trampoline (ENH_BLT0..ENH_BLT6 in src/enhanced.i)."""
import os
import re
import subprocess
import sys
from pathlib import Path

TARGETS = {0x10C: 'ENH_BLT0', 0x112: 'ENH_BLT1', 0x118: 'ENH_BLT4', 0x11E: 'ENH_BLT5',
           0x124: 'ENH_BLT6'}
WAIT = re.compile(r'btst #6,(2\(a6\)|0xdff002)$|jsr 0x(11fde|11fa6|11fc2)$')
FLOW = re.compile(r'(rts|rte|jmp|jsr|bsr|bra|b[a-z]{2}|db[a-z]{1,2})\b')
MEMORY = re.compile(r'\((a[0-57]|sp|pc)[),]|\(a[0-57]\)\+|-\(a[0-57]\)|\(\d|\(-|0x[0-9a-f]{3,}')
START = re.compile(r'move\.w d[01456],88\(a6\)$')


def disassemble(mem, lo, n=160):
    tmp = Path(__file__).resolve().parents[1] / 'tmp' / '.blitsites.bin'
    tmp.write_bytes(mem[lo:lo + n])
    out = subprocess.run(['m68k-amiga-elf-objdump', '-D', '-b', 'binary', '-m', 'm68k:68000',
                          f'--adjust-vma={lo:#x}', str(tmp)], capture_output=True, text=True,
                         check=True).stdout
    os.unlink(tmp)
    rows = []
    for line in out.splitlines():
        m = re.match(r'\s*([0-9a-f]+):\t[0-9a-f ]+\t(.*)', line)
        if m:
            rows.append((int(m.group(1), 16), m.group(2).strip()))
    return rows


def touches_memory(text):
    """True when an instruction reads or writes memory other than the custom chips via a6."""
    if text.startswith('lea') or ' ' not in text:
        return False
    operands = re.sub(r'-?\d*\(a6\)', '', text.split(None, 1)[1])
    return bool(MEMORY.search(operands))


def main(argv):
    mem = open(argv[0], 'rb').read()
    src = Path(__file__).resolve().parents[1] / 'src' / 'blitwait.i'
    sites = [(int(a, 16), int(t, 16)) for a, t in
             re.findall(r'PL_L\s+\$([0-9A-F]+),\$4EB80000\+\$([0-9A-F]+)', src.read_text())]
    found = []
    for a, t in sites:
        rows = disassemble(mem, a)
        if not rows or not START.match(rows[0][1]):
            sys.exit(f'${a:X}: not a blitter start: {rows[0][1] if rows else "?"}')
        for _b, u in rows[1:40]:
            if WAIT.search(u):
                found.append((a, t))
                break
            if FLOW.match(u) or touches_memory(u) or START.match(u):
                break
    print('; Generated by tools/blitsites.py: blitter starts the game waits after itself')
    print(f'; ({len(found)} of {len(sites)} sites; src/enhanced.i, "blitter waits")')
    print('ENH_BLITSITES	MACRO')
    for a, t in found:
        print(f'\t\tPL_L\t${a:X},$4EB80000+{TARGETS[t]}\t; move.w d,$58(a6)')
    print('\t\tENDM')


if __name__ == '__main__':
    main(sys.argv[1:])
