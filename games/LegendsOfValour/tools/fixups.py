#!/usr/bin/env python3
"""Make the version fixup table of the slave from its three language builds.

  python3 tools/fixups.py EN.Slave DE.Slave FR.Slave OUT.s
  python3 tools/fixups.py --same PASS1.Slave FINAL.Slave

The slave's game offsets are hN_OFFSET symbols (src/offsets.s) whose value depends on
LOV_LANG. game.sh assembles the slave once per language (LOV_LANG 0, 1, 2, with LOV_PASS1 so
the table is empty) and this compares them: the builds must have the same size, and every
16-bit word that differs becomes a table entry. The final build is the English one with the
table appended; at boot _lov_fixup writes the German or French words over the English ones.

Table (at the end of the slave): dc.l offset of the table in the slave, number of entries,
then per entry dc.l slave offset, dc.w German word, French word.

--same checks that the final slave starts with the pass-1 English slave, except for the
table's two header longwords, so the table moved no code.
"""
import struct, sys


def code(path):
    b = open(path, 'rb').read()
    l = lambda o: struct.unpack_from('>I', b, o)[0]
    assert l(0) == 0x3f3 and l(8) == 1, '%s: one hunk expected' % path
    o = 24
    assert l(o) & 0x3fffffff == 0x3e9, path
    n = l(o + 4) * 4
    data = b[o + 8:o + 8 + n]
    rest = b[o + 8 + n:]
    assert rest[:4] == b'\0\0\x03\xf2', '%s: relocations in a PIC slave' % path
    return data


def main():
    if sys.argv[1] == '--same':
        p1, final = code(sys.argv[2]), code(sys.argv[3])
        table = len(p1) - 8
        if final[:table] != p1[:table] or len(final) < len(p1):
            raise SystemExit('fixups: the table moved code (%s vs %s)' % (sys.argv[2], sys.argv[3]))
        return
    en, de, fr = (code(p) for p in sys.argv[1:4])
    if not len(en) == len(de) == len(fr):
        raise SystemExit('fixups: the language builds differ in size (%d %d %d): a version-dependent '
                         'value changed an instruction size' % (len(en), len(de), len(fr)))
    table = len(en) - 8
    assert en[table:] == b'\0' * 8, 'pass-1 builds must end with the empty table'
    rows = []
    for o in range(0, table, 2):
        e, d, f = en[o:o + 2], de[o:o + 2], fr[o:o + 2]
        if e != d or e != f:
            rows.append('\t\tdc.l\t$%05x\n\t\tdc.w\t$%s,$%s\n' % (o, d.hex(), f.hex()))
    if any(en[o] != de[o] or en[o] != fr[o] for o in range(table, len(en))):
        raise SystemExit('fixups: the table header differs between languages')
    with open(sys.argv[4], 'w') as out:
        out.write('; Generated by tools/fixups.py from the English, German and French builds.\n'
                  '_lov_fixups\tdc.l\t$%05x,%d\n' % (table, len(rows)) + ''.join(rows))
    print('fixups: %d words' % len(rows))


if __name__ == '__main__':
    main()
