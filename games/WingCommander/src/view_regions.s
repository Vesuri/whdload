; D3: retain native pixel coverage and row/span maps. Only the two flight
; call sites are patched, never the shared clear or composition entries.
; Full-width zero clears use the existing split row table. All other shapes,
; colours, bulk surfaces and nonflight execution tail-call the native routine.
view_clear:
        tst.w   timing_active(pc)
        beq.w   .native
        move.l  4(sp),a0
        tst.l   12(a0)
        bne.w   .native
        tst.b   8(sp)
        bne.w   .native
        cmpi.w  #320,20(a0)
        bne.w   .native
        tst.w   24(a0)
        bne.w   .native
        cmpi.w  #319,28(a0)
        bne.w   .native
        move.w  26(a0),d0
        bmi.w   .native
        move.w  30(a0),d1
        cmpi.w  #200,d1
        bhs.w   .native
        sub.w   d0,d1
        bmi.w   .native
        movem.l d2-d7/a2-a3,-(sp)
        move.l  (a0),a0
        lsl.w   #2,d0
        adda.w  d0,a0
        moveq   #0,d2
        moveq   #0,d3
        moveq   #0,d4
        moveq   #0,d5
        moveq   #0,d6
        moveq   #0,d7
        move.l  d2,a2
        move.l  d2,a3
.row:
        move.l  (a0)+,a1
        rept 10
        movem.l d2-d7/a2-a3,(a1)
        lea     32(a1),a1
        endr
        dbf     d1,.row
        movem.l (sp)+,d2-d7/a2-a3
        rts
.native:
        move.l  timing_game(pc),a0
        lea     E_31cd6(a0),a0
        jmp     (a0)

; Native E:2cf0a interprets 14-byte span records generated by E:2cc36.
; Preserve the map's order, exact leading/trailing bytes and all cockpit gaps.
; No remembered cockpit state: rebuilding the map takes effect immediately.
; Use batching only with the existing cached 020/030 selection. The current
; 040 core measures the native span copier faster; hardware remains uncalibrated.
view_compose:
        tst.w   timing_active(pc)
        beq.w   .native
        cmpi.w  #30,render_selected(pc)
        bne.w   .native
        tst.l   AX_m10d2(a4)
        beq.w   .done
        movem.l d2-d7/a2-a3/a5-a6,-(sp)
        move.l  AX_m10c2(a4),a0
.span:
        move.w  (a0)+,d0
        move.w  (a0)+,d1
        move.w  (a0)+,d2
        move.l  (a0)+,a1
        move.l  (a0)+,a2
        cmpi.w  #4,d0
        beq.w   .end
        ; Tiny native record: -20 - 2*length, length 1..3.
        cmpi.w  #-20,d0
        bgt.s   .regular
        addi.w  #20,d0
        neg.w   d0
        lsr.w   #1,d0
        subq.w  #1,d0
.tiny:
        move.b  (a1)+,(a2)+
        dbf     d0,.tiny
        bra.s   .span
.regular:
        neg.w   d0
        lsr.w   #1,d0
        bra.s   .head_test
.head:
        move.b  (a1)+,(a2)+
.head_test:
        dbf     d0,.head
        neg.w   d1
        lsr.w   #1,d1          ; number of native longword moves
        ; Preserve native longword order for overlapping destinations.
        move.l  a2,d0
        sub.l   a1,d0
        bcs.s   .blocks
        lsr.l   #2,d0
        cmp.w   d1,d0
        blo.s   .long_test
.blocks:
        cmpi.w  #8,d1
        blo.s   .long_test
        movem.l (a1)+,d3-d7/a3/a5-a6
        movem.l d3-d7/a3/a5-a6,(a2)
        lea     32(a2),a2
        subq.w  #8,d1
        bra.s   .blocks
.long:
        move.l  (a1)+,(a2)+
.long_test:
        dbf     d1,.long
        neg.w   d2
        lsr.w   #1,d2
        bra.s   .tail_test
.tail:
        move.b  (a1)+,(a2)+
.tail_test:
        dbf     d2,.tail
        bra.w   .span
.end:
        movem.l (sp)+,d2-d7/a2-a3/a5-a6
.done:
        rts
.native:
        move.l  timing_game(pc),a0
        lea     E_2cf0a(a0),a0
        jmp     (a0)
