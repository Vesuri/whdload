#!/usr/bin/env python3
"""tools/blitsites.py MEMORY.bin [--check MEMORY2.bin ...] > src/blitwait.i

The blitter starts whose wait Enhanced framerate can leave to the game (phase E, step 18).
The original slave turned every `move.w Dn,$58(a6)` in $11000-$19C00 into `jsr $10C-$124.w`:
start the blit, then wait for it. Many are followed, in straight-line code, by the game's
own wait before its next blit (`btst #6,2(a6)` or `btst #6,$DFF002`, or `jsr $1123A`,
`$11202`, `$1121E`). A site qualifies when every instruction up to that wait touches no
memory but the custom chips through a6 (a `lea` is fine): no branch, call or return, no
other blitter start, no CPU access that might meet the blit.

MEMORY.bin is a 512 KB chip memory image taken in a race (the slave's patches applied, so the
sites read `jsr $1xx.w`); each --check image must have the same instruction at every site.
Writes the patch list body: one PL_W per site, pointing its `jsr` at the matching
trampoline (ENH_BLT0..ENH_BLT6 in src/enhanced.i)."""
import os
import re
import subprocess
import sys

LO, HI = 0x11000, 0x19C00
TARGETS = {0x10C: 'ENH_BLT0', 0x112: 'ENH_BLT1', 0x118: 'ENH_BLT4', 0x11E: 'ENH_BLT5',
           0x124: 'ENH_BLT6'}
WAIT = re.compile(r'btst #6,(2\(a6\)|0xdff002)$|jsr 0x(1123a|11202|1121e)$')
FLOW = re.compile(r'(rts|rte|jmp|jsr|bsr|bra|b[a-z]{2}|db[a-z]{1,2})\b')
MEMORY = re.compile(r'\((a[0-57]|sp|pc)[),]|\(a[0-57]\)\+|-\(a[0-57]\)|\(\d|\(-|0x[0-9a-f]{3,}')


def disassemble(image):
    tmp = os.path.join(os.path.dirname(os.path.abspath(image)), '.blitsites.bin')
    with open(image, 'rb') as f, open(tmp, 'wb') as out:
        f.seek(LO)
        out.write(f.read(HI - LO + 64))
    out = subprocess.run(['m68k-amiga-elf-objdump', '-D', '-b', 'binary', '-m', 'm68k:68000',
                          f'--adjust-vma={LO:#x}', tmp], capture_output=True, text=True,
                         check=True).stdout
    os.unlink(tmp)
    rows = []
    for line in out.splitlines():
        m = re.match(r'\s*([0-9a-f]+):\t[0-9a-f ]+\t(.*)', line)
        if m:
            rows.append((int(m.group(1), 16), m.group(2).strip()))
    return rows


def touches_memory(text):
    """True when an instruction reads or writes memory other than the custom chips via a6."""
    if text.startswith('lea') or ' ' not in text:
        return False
    operands = re.sub(r'-?\d*\(a6\)', '', text.split(None, 1)[1])
    return bool(MEMORY.search(operands))


def sites(rows):
    found = []
    for i, (a, text) in enumerate(rows):
        m = re.fullmatch(r'jsr 0x(10c|112|118|11e|124)', text)
        if not m or a >= HI:
            continue
        for _b, u in rows[i + 1:i + 40]:
            if WAIT.search(u):
                found.append((a, int(m.group(1), 16)))
                break
            if FLOW.match(u) or touches_memory(u):
                break
    return found


def main(argv):
    image = argv[0]
    checks = argv[argv.index('--check') + 1:] if '--check' in argv else []
    found = sites(disassemble(image))
    for other in checks:
        mem = open(other, 'rb').read()
        bad = [a for a, t in found if mem[a:a + 4] != bytes([0x4E, 0xB8, t >> 8, t & 0xFF])]
        if bad:
            sys.exit(f'{other}: not the same at {" ".join(f"${a:X}" for a in bad)}')
    print('; Generated by tools/blitsites.py: blitter starts the game waits after itself')
    print(f'; ({len(found)} sites; src/enhanced.i, "blitter waits")')
    for a, t in found:
        print(f'\t\tPL_W\t${a + 2:X},{TARGETS[t]}\t; jsr ${t:X}.w')


if __name__ == '__main__':
    main(sys.argv[1:])
