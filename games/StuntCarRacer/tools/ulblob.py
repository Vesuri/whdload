#!/usr/bin/env python3
"""Build the Unleashed blob (src/unleashed.s) for the slave, and check its patch table.

    python3 -I tools/ulblob.py OUTDIR [--define NAME=VALUE ...] [--original PROGRAM]

Assembles src/unleashed.s twice as a raw binary, with O=0 and O=$100000 (every address in
the program and in the blob moved by that much). The longwords that differ by exactly
$100000 are the blob's relocations; any other difference is an error (an address that
does not move whole, such as one truncated to a word). Writes OUTDIR/unleashed.bin (the
O=0 build) and OUTDIR/unleashed.i, which the slave includes: UL_CODE and UL_SIZE (the code,
and the code with what it reserves behind it) and ulRelocs, the relocation table in the
format of relocTable (src/relocs.s), its distances counted from 2 bytes before the blob.

--original PROGRAM (the decrypted main program at $e700, tools/scr_extract.py) checks the
patch table against it: every patch must start and end on the original's instruction
boundaries and cover no branch target other than its first instruction (the targets of
every branch, jsr and jmp a recursive descent of the original finds, and every address
relocTable relocates). A patch in chip memory (the copper list, CHIP_PATCHES) is not
checked.
"""
import argparse
import os
import re
import struct
import subprocess
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from unleashed_diff import BASE, CHIP, reachable  # noqa: E402

from capstone import Cs, CS_ARCH_M68K, CS_MODE_M68K_000, CS_MODE_BIG_ENDIAN  # noqa: E402
from capstone import m68k as M  # noqa: E402

ORG = 0x722e0           # the blob's address, right after the program ($e700-$722e0)
SHIFT = 0x100000
IMAGE_END = 0x722e0
RANGES = [(0xe700, 0xf472), (0x1b74a, 0x1b900), (0x1ba08, 0x1baf8), (0x57000, 0x6a166)]
# Chip memory a patch may write that is not in CHIP: the chip original's own start-up code,
# which never runs once the copy does.
CHIP_PATCHES = {
    0xe74a: "the start-up jmp's operand: the wait in front of the copper list",
}
# Patches that end inside an original instruction on purpose.
PARTIAL = {
    0x6646e: "applyBitplaneMask's bra.w keeps its displacement: lbB057D75, the mode the game writes",
}
GAME = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def assemble(src, out, defines):
    vasm = os.environ.get('VASM', 'vasmm68k_mot')
    cmd = [vasm, '-quiet', '-Fbin', '-m68000', '-no-opt', '-I' + os.path.dirname(src)]
    cmd += ['-D' + d for d in defines] + ['-o', out, src]
    r = subprocess.run(cmd, capture_output=True, text=True)
    if r.returncode:
        sys.exit(r.stdout + r.stderr)
    return open(out, 'rb').read()


def relocations(b0, b1):
    if len(b0) != len(b1):
        sys.exit('the two builds differ in size: %d and %d' % (len(b0), len(b1)))
    sites = []
    i = 0
    while i < len(b0):
        if b0[i] == b1[i]:
            i += 1
            continue
        s = i - 1       # $100000 changes the second byte of a longword below $f00000
        if s < 0 or s % 2 or struct.unpack_from('>L', b1, s)[0] - struct.unpack_from('>L', b0, s)[0] != SHIFT:
            sys.exit('a difference at blob offset $%x that is not an address' % i)
        sites.append(s)
        i = s + 4
    return sites


def write_include(path, sites, code, bss):
    with open(path, 'w') as f:
        f.write('; Generated by tools/ulblob.py from src/unleashed.s: do not edit.\n')
        f.write('UL_CODE\t= %d\n' % code)
        f.write('UL_SIZE\t= %d\n' % (code + bss))
        f.write('ulRelocs:\n')
        prev = -2       # the table starts 2 bytes before the blob: no distance is 0
        for s in sites:
            d = s - prev
            if 0 < d < 0x10000:
                f.write('\tdc.w\t$%04x\n' % d)
            else:
                f.write('\tdc.w\t0\n\tdc.l\t$%x\n' % d)
            prev = s
        f.write('\tdc.w\t0\n\tdc.l\t0\n')


def patches(b0):
    """[(site, length, chip)] from the patch table."""
    table = struct.unpack_from('>L', b0, 12)[0] - ORG
    out = []
    while True:
        site = struct.unpack_from('>L', b0, table)[0]
        if not site:
            return out
        n = struct.unpack_from('>H', b0, table + 4)[0]
        out.append((site, n, site in CHIP_PATCHES or any(c0 <= site < c1 for c0, c1 in CHIP)))
        table += 6 + n


def check(original, table):
    orig = open(original, 'rb').read()
    code = reachable(orig, RANGES, IMAGE_END)
    md = Cs(CS_ARCH_M68K, CS_MODE_M68K_000 | CS_MODE_BIG_ENDIAN)
    md.detail = True
    targets = {}
    for a in code:
        for ins in md.disasm(orig[a - BASE:a - BASE + 10], a, 1):
            for op in ins.operands:
                if op.type == M.M68K_OP_BR_DISP:
                    targets.setdefault(ins.address + 2 + op.br_disp.disp, a)
                elif (op.type == M.M68K_OP_MEM and op.address_mode == M.M68K_AM_ABSOLUTE_DATA_LONG
                      and ins.mnemonic.split('.')[0] in ('jsr', 'jmp')):
                    targets.setdefault(op.imm & 0xffffffff, a)
    rx = re.compile(r'; \$([0-9a-f]{5}) \$([0-9a-f]{5}) ')
    for line in open(os.path.join(GAME, 'src', 'relocs.s')):
        m = rx.search(line)
        if m:
            targets.setdefault(int(m.group(2), 16), int(m.group(1), 16))
    ends = {a + s for a, (s, _, _) in code.items()}
    bad = 0
    for site, n, chip in table:
        if chip:
            continue
        end = site + n
        why = []
        if site not in code:
            why.append('starts inside an instruction')
        if end not in code and end not in ends and site not in PARTIAL:
            why.append('ends inside an instruction')
        for t, frm in sorted(targets.items()):
            if site < t < end:
                why.append('$%05x is a target (from $%05x)' % (t, frm))
        if why:
            bad += 1
            print('patch $%05x-$%05x: %s' % (site, end, '; '.join(why)))
    print('%d patches checked, %d with problems' % (len(table), bad), file=sys.stderr)
    return bad


def main():
    p = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    p.add_argument('outdir')
    p.add_argument('--define', action='append', default=[])
    p.add_argument('--original')
    a = p.parse_args()
    src = os.path.join(GAME, 'src', 'unleashed.s')
    os.makedirs(a.outdir, exist_ok=True)
    b0 = assemble(src, os.path.join(a.outdir, 'unleashed.bin'), a.define + ['O=0'])
    b1 = assemble(src, os.path.join(a.outdir, 'unleashed.o1'), a.define + ['O=$%x' % SHIFT])
    os.remove(os.path.join(a.outdir, 'unleashed.o1'))
    if struct.unpack_from('>L', b0, 0)[0] - ORG >= len(b0):
        sys.exit('src/unleashed.s does not start with its header at $%x' % ORG)
    sites = relocations(b0, b1)
    bss = struct.unpack_from('>L', b0, 8)[0]
    write_include(os.path.join(a.outdir, 'unleashed.i'), sites, len(b0), bss)
    print('unleashed.bin: %d bytes, %d relocations, %d reserved' % (len(b0), len(sites), bss), file=sys.stderr)
    if a.original:
        return 1 if check(a.original, patches(b0)) else 0
    return 0


if __name__ == '__main__':
    sys.exit(main())
